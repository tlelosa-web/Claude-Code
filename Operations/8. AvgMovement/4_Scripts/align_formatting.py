"""
Format Alignment Script
Reads the 'Item Movement Summary' tab from Item Movement [date].xlsx
and applies the same column structure and formatting to all category tabs
in Item Movement By Cat [date].xlsx

Note: This script ensures formatting consistency. For data regeneration
with updated columns (e.g., adding Re-Order Point), run item_movement_by_cat.py
"""

import os
import sys
from openpyxl import load_workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.worksheet.properties import PageSetupProperties

# ── Paths ─────────────────────────────────────────────────────────────
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
OUTPUT_DIR = os.path.join(PROJECT_ROOT, "3_Live_Reports")

TODAY = "22.04.2026"
SOURCE_FILE = os.path.join(OUTPUT_DIR, f"Item Movement {TODAY}.xlsx")
TARGET_FILE = os.path.join(OUTPUT_DIR, f"Item Movement By Cat {TODAY}.xlsx")

def log(msg: str):
    print(msg)


def get_source_formatting(source_path: str):
    """Extract formatting information from the Item Movement Summary tab."""
    if not os.path.exists(source_path):
        log(f"ERROR: Source file not found: {source_path}")
        return None
    
    log(f"Reading source file: {source_path}")
    wb = load_workbook(source_path)
    
    if "Item Movement Summary" not in wb.sheetnames:
        log("ERROR: 'Item Movement Summary' tab not found in source file")
        return None
    
    ws = wb["Item Movement Summary"]
    
    # Extract headers
    headers = []
    for cell in ws[1]:
        if cell.value:
            headers.append(cell.value)
        else:
            break
    
    log(f"Found {len(headers)} columns in Item Movement Summary:")
    for i, h in enumerate(headers, 1):
        log(f"  Column {i}: {h}")
    
    # Extract number formats from second row
    number_formats = {}
    if ws.max_row > 1:
        for col_idx in range(1, len(headers) + 1):
            cell = ws.cell(row=2, column=col_idx)
            if cell.number_format and cell.number_format != 'General':
                number_formats[col_idx] = cell.number_format
    
    # Extract table properties
    table_info = {
        "headers": headers,
        "number_formats": number_formats,
        "page_setup": {
            "orientation": ws.page_setup.orientation,
            "fitToWidth": ws.page_setup.fitToWidth,
            "fitToHeight": ws.page_setup.fitToHeight,
        },
        "print_options": {
            "horizontalCentered": ws.print_options.horizontalCentered,
        },
        "margins": {
            "left": ws.page_margins.left,
            "right": ws.page_margins.right,
        }
    }
    
    wb.close()
    return table_info


def apply_formatting_to_target(target_path: str, table_info: dict):
    """Apply the extracted formatting to all category tabs in the target file."""
    if not os.path.exists(target_path):
        log(f"ERROR: Target file not found: {target_path}")
        return False
    
    log(f"\nApplying formatting to: {target_path}")
    wb = load_workbook(target_path)
    
    headers = table_info["headers"]
    num_cols = len(headers)
    max_col_letter = get_column_letter(num_cols)
    
    sheets_modified = 0
    
    for sheet_name in wb.sheetnames:
        if sheet_name == "Category Summary":
            log(f"  Skipping '{sheet_name}' (summary tab)")
            continue
        
        log(f"  Processing tab: '{sheet_name}'")
        ws = wb[sheet_name]
        
        # Check current headers
        current_headers = []
        for cell in ws[1]:
            if cell.value:
                current_headers.append(cell.value)
            else:
                break
        
        log(f"    Current columns: {len(current_headers)}")
        log(f"    Target columns: {num_cols}")
        
        if len(current_headers) != num_cols:
            log(f"    ⚠️  Column count mismatch! Need to restructure...")
            
            # Clear existing data and rebuild with correct headers
            ws.delete_rows(1, ws.max_row)
            
            # Add correct headers
            ws.append(headers)
            
            # Note: Data will need to be regenerated by running the main script
            log(f"    Headers updated. Please regenerate data using item_movement_by_cat.py")
        else:
            # Just verify headers match
            if current_headers == headers:
                log(f"    ✓ Headers already match")
            else:
                log(f"    ⚠️  Headers differ, updating...")
                for col_idx, header in enumerate(headers, 1):
                    ws.cell(row=1, column=col_idx, value=header)
        
        # Apply number formats
        if table_info["number_formats"]:
            for col_idx, fmt in table_info["number_formats"].items():
                for row in ws.iter_rows(min_row=2, max_row=ws.max_row, min_col=col_idx, max_col=col_idx):
                    for cell in row:
                        cell.number_format = fmt
        
        # Apply page setup
        ws.sheet_properties.pageSetUpPr = PageSetupProperties(fitToPage=True)
        ws.page_setup.orientation = table_info["page_setup"]["orientation"]
        ws.page_setup.fitToWidth = table_info["page_setup"]["fitToWidth"]
        ws.page_setup.fitToHeight = table_info["page_setup"]["fitToHeight"]
        ws.print_options.horizontalCentered = table_info["print_options"]["horizontalCentered"]
        ws.page_margins.left = table_info["margins"]["left"]
        ws.page_margins.right = table_info["margins"]["right"]
        ws.print_title_rows = "1:1"
        
        # Freeze panes
        ws.freeze_panes = "A2"
        
        sheets_modified += 1
        log(f"    ✓ Formatting applied")
    
    # Save
    backup_path = target_path.replace(".xlsx", "_backup.xlsx")
    if os.path.exists(backup_path):
        os.remove(backup_path)
    os.rename(target_path, backup_path)
    log(f"\nBackup created: {backup_path}")
    
    wb.save(target_path)
    log(f"Saved updated file: {target_path}")
    log(f"✓ Modified {sheets_modified} tabs")
    
    return True


def main():
    log("=" * 70)
    log("Format Alignment Tool")
    log("=" * 70)
    
    # Step 1: Extract formatting from source
    log("\nStep 1: Extracting formatting from source file...")
    table_info = get_source_formatting(SOURCE_FILE)
    
    if not table_info:
        log("❌ Failed to extract formatting")
        sys.exit(1)
    
    # Step 2: Apply to target
    log("\nStep 2: Applying formatting to target file...")
    success = apply_formatting_to_target(TARGET_FILE, table_info)
    
    if success:
        log("\n" + "=" * 70)
        log("✅ FORMAT ALIGNMENT COMPLETE")
        log("=" * 70)
        log("\nIMPORTANT:")
        log("If column counts didn't match, you need to regenerate the data")
        log("by running: python 4_Scripts/item_movement_by_cat.py")
    else:
        log("\n❌ Format alignment failed")
        sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        log(f"\n❌ ERROR: {e}")
        import traceback
        log(traceback.format_exc())
        sys.exit(1)
